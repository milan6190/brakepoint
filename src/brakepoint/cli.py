import json
import os
import shlex
import subprocess
import sys
from pathlib import Path

from . import __version__
from .actions import Action
from .approval import QueueApprover, build_approver
from .audit import AuditLog
from .catalog import load_catalog
from .engine import Engine
from .incidents import INCIDENTS
from .policy import DEFAULT_POLICY_YAML, Policy

EXIT_OK, EXIT_APPROVE, EXIT_DENY = 0, 3, 4
_COLORS = {"allow": "32", "log": "36", "approve": "33", "deny": "31"}


def _color(text: str, decision: str) -> str:
    if not sys.stdout.isatty() or os.environ.get("NO_COLOR"):
        return text
    return f"\033[{_COLORS.get(decision, '0')}m{text}\033[0m"


def _action_from_args(args) -> Action:
    text = " ".join(args.text)
    if args.kind == "tool":
        name, _, rest = text.partition(" ")
        payload = json.loads(rest) if rest.strip() else {}
        return Action.tool(name, payload)
    return {
        "shell": Action.shell,
        "sql": Action.sql,
        "url": Action.url,
        "file": lambda t: Action.file(t, "write"),
    }[args.kind](text)


# ---------------------------------------------------------------- commands
def cmd_check(args) -> int:
    policy = Policy.load(args.policy)
    verdict = Engine(policy).evaluate(_action_from_args(args))
    if args.json:
        print(json.dumps(verdict.to_dict(), indent=2))
    else:
        print(_color(verdict.decision.upper(), verdict.decision), end="")
        if verdict.matches:
            print("\n" + verdict.reason("human"))
        else:
            print("  no catalogued risk")
    return {"approve": EXIT_APPROVE, "deny": EXIT_DENY}.get(verdict.decision, EXIT_OK)


def cmd_exec(args) -> int:
    if not args.command:
        print("usage: brakepoint exec -- <command> [args...]", file=sys.stderr)
        return 2
    command = args.command[0] if len(args.command) == 1 else shlex.join(args.command)
    policy = Policy.load(args.policy)
    verdict = Engine(policy).evaluate(Action.shell(command, origin="exec"))
    audit = AuditLog(policy.audit_path, policy.audit_enabled)

    if verdict.decision == "approve":
        result = build_approver(policy).request(verdict)
        audit.record(verdict, "approved" if result.approved else "rejected", approver=result.approver)
        if not result.approved:
            print(verdict.reason("agent") + f"\nNot approved: {result.detail}", file=sys.stderr)
            return EXIT_DENY
    elif verdict.decision == "deny":
        audit.record(verdict, "blocked")
        print(verdict.reason("agent"), file=sys.stderr)
        return EXIT_DENY
    elif verdict.decision == "log":
        audit.record(verdict, "allowed")

    if len(args.command) == 1:
        return subprocess.call(command, shell=True)
    return subprocess.call(args.command)


def cmd_hook(args) -> int:
    if args.harness != "claude-code":
        print(f"unknown harness {args.harness!r}", file=sys.stderr)
        return 2
    from .integrations.claude_code import main

    return main(policy_path=args.policy)


def cmd_mcp_proxy(args) -> int:
    from .integrations.mcp_proxy import McpProxy

    if not args.server:
        print("usage: brakepoint mcp-proxy --name NAME -- <server command>", file=sys.stderr)
        return 2
    return McpProxy(args.server, args.name, Policy.load(args.policy)).run()


def _queue(args) -> QueueApprover:
    policy = Policy.load(args.policy)
    return QueueApprover(policy.queue_dir, policy.approval_timeout)


def cmd_pending(args) -> int:
    items = _queue(args).pending()
    if not items:
        print("No pending approvals.")
    for item in items:
        print(f"[{item['id']}] {item['created']}\n{item['summary']}\n")
    return 0


def cmd_decide(args) -> int:
    ok = _queue(args).decide(args.id, approve=(args.command_name == "approve"))
    if not ok:
        print(f"No pending request {args.id}.", file=sys.stderr)
        return 1
    print(f"{args.command_name.capitalize()}d {args.id}.")
    return 0


def cmd_catalog(args) -> int:
    policy = Policy.load(args.policy)
    rules = [r for r in load_catalog(policy.catalogs) if not args.platform or r.platform == args.platform]
    if args.json:
        print(json.dumps([r.to_dict() for r in rules], indent=2))
        return 0
    if args.markdown:
        print(_catalog_markdown(rules))
        return 0
    for r in rules:
        lock = " (locked)" if r.locked else ""
        print(f"{r.id:<12} {r.severity:<9} {r.platform:<11} {r.title}{lock}")
    print(f"\n{len(rules)} rules")
    return 0


def _catalog_markdown(rules) -> str:
    out = [
        "# Destructive-action catalog",
        "",
        (
            "Generated by `brakepoint catalog --markdown`. Do not edit by hand; edit the YAML in "
            "`src/brakepoint/catalog/` and regenerate."
        ),
        "",
        f"{len(rules)} rules.",
        "",
    ]
    platforms = []
    for r in rules:
        if r.platform not in platforms:
            platforms.append(r.platform)
    for platform in platforms:
        out += [
            f"## {platform}",
            "",
            "| ID | Severity | Reversibility | Category | What it catches | Safer alternative |",
            "|---|---|---|---|---|---|",
        ]
        for r in rules:
            if r.platform != platform:
                continue
            title = r.title + (" **(locked)**" if r.locked else "")
            out.append(f"| `{r.id}` | {r.severity} | {r.reversibility} | {r.category} | {title} | {r.safer} |")
        out.append("")
    return "\n".join(out)


def cmd_audit(args) -> int:
    policy = Policy.load(args.policy)
    log = AuditLog(args.path or policy.audit_path)
    if args.action == "verify":
        ok, message = log.verify()
        print(("OK: " if ok else "TAMPERED: ") + message)
        return 0 if ok else 1
    lines = list(log.entries() or [])
    for _, line in lines[-args.n :]:
        e = json.loads(line)
        rules = ",".join(m["rule"] for m in e.get("matches", []))
        print(f"{e['ts']}  {e['outcome']:<9} {e['decision']:<8} {rules:<24} {e['action']['text'][:80]}")
    return 0


def cmd_init(args) -> int:
    target = Path(".brakepoint.yaml")
    if target.exists() and not args.force:
        print(f"{target} already exists (use --force to overwrite).")
    else:
        target.write_text(DEFAULT_POLICY_YAML)
        print(f"Wrote {target}.")
    if args.claude_code:
        settings = Path(".claude/settings.json")
        settings.parent.mkdir(exist_ok=True)
        data = json.loads(settings.read_text()) if settings.exists() else {}
        hooks = data.setdefault("hooks", {}).setdefault("PreToolUse", [])
        entry = {
            "matcher": "Bash|Write|Edit|MultiEdit|NotebookEdit|Read|WebFetch|mcp__.*",
            "hooks": [{"type": "command", "command": "brakepoint hook claude-code", "timeout": 600}],
        }
        if not any("brakepoint hook" in json.dumps(h) for h in hooks):
            hooks.append(entry)
            settings.write_text(json.dumps(data, indent=2) + "\n")
            print(f"Added the Brakepoint PreToolUse hook to {settings}.")
        else:
            print(f"{settings} already has a Brakepoint hook.")
    return 0


def cmd_replay(args) -> int:
    policy = Policy.load(args.policy) if args.policy else Policy()
    engine = Engine(policy)
    missed = 0
    for incident in INCIDENTS:
        if args.id and incident.id != args.id:
            continue
        print(f"\n{incident.title}  ({incident.when})")
        print(f"  {incident.summary}")
        print(f"  Source: {incident.source}")
        for label, action in incident.steps:
            verdict = engine.evaluate(action)
            top = verdict.top.rule.id if verdict.top else "-"
            mark = _color(f"{verdict.decision.upper():<8}", verdict.decision)
            print(f"   {mark} {top:<12} {label}")
            if verdict.decision in ("allow", "log"):
                missed += 1
    print()
    if missed:
        print(f"{missed} step(s) would NOT have been stopped.")
        return 1
    print("Every step would have been stopped for a human decision.")
    return 0


# ---------------------------------------------------------------- parser
def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="brakepoint",
        description="A breakpoint for irreversible AI agent actions.",
    )
    parser.add_argument("--version", action="version", version=f"brakepoint {__version__}")
    parser.add_argument("--policy", help="policy file (default: .brakepoint.yaml found from the current directory)")
    sub = parser.add_subparsers(dest="command_name", required=True)
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--policy", default=argparse.SUPPRESS, help=argparse.SUPPRESS)

    p = sub.add_parser("check", parents=[common], help="classify an action without running it")
    p.add_argument("--kind", choices=["shell", "sql", "tool", "file", "url"], default="shell")
    p.add_argument("--json", action="store_true")
    p.add_argument("text", nargs="+", help='command, SQL, URL, path, or "<tool_name> <json args>"')
    p.set_defaults(func=cmd_check)

    p = sub.add_parser("exec", parents=[common], help="run a shell command through Brakepoint")
    p.add_argument("command", nargs=argparse.REMAINDER)
    p.set_defaults(func=cmd_exec)

    p = sub.add_parser("hook", parents=[common], help="run as an agent-harness hook (reads the tool call on stdin)")
    p.add_argument("harness", choices=["claude-code"])
    p.set_defaults(func=cmd_hook)

    p = sub.add_parser("mcp-proxy", parents=[common], help="guard a stdio MCP server")
    p.add_argument("--name", required=True, help="server name, used in rules and audit")
    p.add_argument("server", nargs=argparse.REMAINDER)
    p.set_defaults(func=cmd_mcp_proxy)

    p = sub.add_parser("pending", parents=[common], help="list approvals waiting in the queue")
    p.set_defaults(func=cmd_pending)
    for name in ("approve", "deny"):
        p = sub.add_parser(name, parents=[common], help=f"{name} a queued request")
        p.add_argument("id")
        p.set_defaults(func=cmd_decide)

    p = sub.add_parser("catalog", parents=[common], help="list the destructive-action catalog")
    p.add_argument("--platform")
    group = p.add_mutually_exclusive_group()
    group.add_argument("--json", action="store_true")
    group.add_argument("--markdown", action="store_true")
    p.set_defaults(func=cmd_catalog)

    p = sub.add_parser("audit", parents=[common], help="inspect or verify the audit log")
    p.add_argument("action", choices=["tail", "verify"])
    p.add_argument("-n", type=int, default=20)
    p.add_argument("--path")
    p.set_defaults(func=cmd_audit)

    p = sub.add_parser("init", parents=[common], help="write a starter policy (and optionally the Claude Code hook)")
    p.add_argument("--claude-code", action="store_true", help="also add the hook to .claude/settings.json")
    p.add_argument("--force", action="store_true")
    p.set_defaults(func=cmd_init)

    p = sub.add_parser("replay", parents=[common], help="replay publicly reported agent incidents against your policy")
    p.add_argument("id", nargs="?")
    p.set_defaults(func=cmd_replay)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if getattr(args, "command", None) and args.command[:1] == ["--"]:
        args.command = args.command[1:]
    if getattr(args, "server", None) and args.server[:1] == ["--"]:
        args.server = args.server[1:]
    return args.func(args)


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
