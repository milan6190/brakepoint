"""Rule coverage, reported next to pass/fail.

A green test run says the cases we wrote behave as expected. It does not say every
rule is exercised, and it is not conformance with any standard. This plugin records
which rules each test triggers and prints the gaps in the test summary.
Lives at the repo root so pytest always registers --rule-coverage.
Write the full report with:  pytest --rule-coverage docs/COVERAGE.md
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

import pytest

from brakepoint import engine as engine_module
from brakepoint.catalog import load_catalog

_HITS: dict[str, set[str]] = defaultdict(set)
_CURRENT = {"test": ""}
SYNTHETIC = {
    "BP-SELF-002": "brakepoint",
    "BP-SIZE-001": "brakepoint",
    "BP-HINT-001": "mcp",
}


def pytest_addoption(parser):
    parser.addoption("--rule-coverage", metavar="PATH", help="write a Markdown rule-coverage report to PATH")
    parser.addoption(
        "--require-all-rules", action="store_true", help="fail the run if any rule is never triggered by a test"
    )


def pytest_configure(config):
    original = engine_module.Engine.evaluate

    def recording(self, action, extra_matches=None):
        verdict = original(self, action, extra_matches)
        for match in verdict.matches:
            _HITS[match.rule.id].add(_CURRENT["test"])
        return verdict

    engine_module.Engine.evaluate = recording


def pytest_sessionfinish(session, exitstatus):
    untested = any(r[4] == 0 for r in _rows())
    if session.config.getoption("--require-all-rules") and exitstatus == 0 and untested:
        session.exitstatus = 1


def pytest_runtest_setup(item):
    _CURRENT["test"] = item.nodeid


def _rows():
    rules = [(r.id, r.platform, r.severity, r.title) for r in load_catalog()]
    rules += [(rid, platform, "-", "(engine rule)") for rid, platform in SYNTHETIC.items()]
    return [(rid, platform, sev, title, len(_HITS.get(rid, ()))) for rid, platform, sev, title in rules]


def pytest_terminal_summary(terminalreporter):
    rows = _rows()
    if not _HITS:  # a partial run (-k) that never evaluated anything
        return
    untested = [r[0] for r in rows if r[4] == 0]
    terminalreporter.section("rule coverage")
    terminalreporter.write_line(
        f"{len(rows) - len(untested)}/{len(rows)} rules triggered by at least one test. "
        "Pass/fail covers only these cases; it is not conformance with AISVS or any other standard."
    )
    if untested:
        terminalreporter.write_line("Never triggered: " + ", ".join(untested))
        if terminalreporter.config.getoption("--require-all-rules"):
            terminalreporter.write_line("FAILED: every rule needs at least one test (--require-all-rules).")
    path = terminalreporter.config.getoption("--rule-coverage")
    if path:
        Path(path).write_text(_markdown(rows), encoding="utf-8")
        terminalreporter.write_line(f"Wrote {path}")


def _markdown(rows) -> str:
    tested = sum(1 for r in rows if r[4])
    out = [
        "# Rule coverage",
        "",
        "Generated by `pytest --rule-coverage docs/COVERAGE.md`. Do not edit by hand.",
        "",
        f"**{tested} of {len(rows)} rules** are triggered by at least one test.",
        "",
        "Read this next to the test results. A passing suite means the cases below behave as",
        "expected. It does not mean a rule catches every phrasing of its action, that untested",
        "rules work, or that Brakepoint meets any standard. See",
        "[THREAT_MODEL.md](THREAT_MODEL.md#non-goals) for what is out of scope and",
        "[CROSSWALK.md](CROSSWALK.md) for how rules and tests relate to AISVS and NIST.",
        "",
        "| Rule | Platform | Severity | What it catches | Tests that trigger it |",
        "|---|---|---|---|---|",
    ]
    for rid, platform, sev, title, hits in rows:
        out.append(f"| `{rid}` | {platform} | {sev} | {title} | {hits if hits else '**none**'} |")
    return "\n".join(out) + "\n"


@pytest.fixture(autouse=True)
def _no_user_policy(monkeypatch):
    """Keep tests independent of the developer's own BRAKEPOINT_POLICY."""
    monkeypatch.delenv("BRAKEPOINT_POLICY", raising=False)
